#Se realiza la preparación de datos
def preparar_datos(data):
    data_preparada = data.copy()

    #En despliegue drop_first= False
    data_preparada = pd.get_dummies(data_preparada, columns=['smoking_status', 'hypertension', 'heart_disease', 'ever_married'], drop_first=False, dtype=int)

    #Se adicionan las columnas faltantes
    data_preparada = data_preparada.reindex(columns=variables, fill_value=0)

    #Se normalizan la edad y la glucosa porque el modelo es un SVM (Knn, Red, SVM, Reg se normalizan)
    #En los despliegues no se llama fit
    data_preparada[['age', 'avg_glucose_level']] = min_max_scaler.transform(data_preparada[['age', 'avg_glucose_level']])
    return data_preparada

#Predicciones

#Hacemos la predicción con el SVM
def predecir(data):
    data_preparada = preparar_datos(data)
    Y_pred = modelo.predict(data_preparada)

    resultado = data.copy()
    resultado['Prediccion'] = labelencoder.inverse_transform(Y_pred)   #Yes: con riesgo, No: sin riesgo
    resultado['Puntaje'] = modelo.decision_function(data_preparada)    #Distancia a la frontera del SVM (positivo: riesgo)
    return resultado, data_preparada

